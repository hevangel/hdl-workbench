import type {
  CompileRequest,
  CompileResult,
  FileEntry,
  ProjectPath,
  RunRequest,
  RunResult,
  SnapshotFile,
  WorkspaceAdapter,
  SimulationService,
} from "@xezim-ide/protocol";

const encoder = new TextEncoder();
const decoder = new TextDecoder();

const initialFiles: Array<{ path: ProjectPath; content: string }> = [
  {
    path: "rtl/counter.sv",
    content: `module counter #(parameter WIDTH = 4) (
  input logic clk,
  input logic rst_n,
  output logic [WIDTH-1:0] count
);
  always_ff @(posedge clk) begin
    if (!rst_n) count <= '0;
    else count <= count + 1'b1;
  end
endmodule
`,
  },
  {
    path: "tb/counter_tb.sv",
    content: `module counter_tb;
  logic clk = 0;
  logic rst_n = 0;
  logic [3:0] count;

  counter dut(.clk(clk), .rst_n(rst_n), .count(count));
  always #5 clk = ~clk;

  initial begin
    #12 rst_n = 1;
    #80 $finish;
  end
endmodule
`,
  },
];

export function createMockServices(): { workspace: WorkspaceAdapter; simulation: SimulationService } {
  const fileStore = new Map<ProjectPath, { bytes: Uint8Array; revision: string }>(
    initialFiles.map(({ path, content }, index) => [path, { bytes: encoder.encode(content), revision: `mock-rev-${index + 1}` }]),
  );
  const snapshots = new Map<string, SnapshotFile[]>();
  const listeners = new Set<(change: { path: ProjectPath; revision: string | null; operation: "write" | "delete" }) => void>();
  let revisionCounter = fileStore.size + 1;
  let snapshotCounter = 0;
  let compileCounter = 0;
  let runCounter = 0;

  const workspace: WorkspaceAdapter = {
    async listFiles(): Promise<FileEntry[]> {
      return [...fileStore.entries()].map(([path, item]) => ({
        path,
        revision: item.revision,
        sizeBytes: item.bytes.byteLength,
      }));
    },
    async readFile(path) {
      const file = fileStore.get(path);
      if (!file) throw new Error(`NOT_FOUND: ${path}`);
      return { bytes: file.bytes.slice(), revision: file.revision };
    },
    async writeFile(path, bytes, expectedRevision) {
      const current = fileStore.get(path);
      if ((current?.revision ?? null) !== expectedRevision) throw new Error("REVISION_CONFLICT");
      const revision = `mock-rev-${revisionCounter++}`;
      fileStore.set(path, { bytes: bytes.slice(), revision });
      for (const listener of listeners) listener({ path, revision, operation: "write" });
      return { revision };
    },
    async deleteFile(path, expectedRevision) {
      const current = fileStore.get(path);
      if (!current) throw new Error(`NOT_FOUND: ${path}`);
      if (current.revision !== expectedRevision) throw new Error("REVISION_CONFLICT");
      fileStore.delete(path);
      for (const listener of listeners) listener({ path, revision: null, operation: "delete" });
    },
    async snapshot() {
      const snapshotId = `mock-snapshot-${++snapshotCounter}`;
      const files = [...fileStore.entries()].map(([path, file]) => ({
        path,
        revision: file.revision,
        bytes: file.bytes.slice(),
      }));
      snapshots.set(snapshotId, files);
      return { snapshotId, files: files.map((file) => ({ ...file, bytes: file.bytes.slice() })) };
    },
    subscribeChanges(callback) {
      listeners.add(callback);
      return () => listeners.delete(callback);
    },
  };

  const simulation: SimulationService = {
    async compile(input: CompileRequest): Promise<CompileResult> {
      const files = snapshots.get(input.snapshotId) ?? [];
      const sourceFile = files.find((file) => file.path.endsWith(".sv") && decoder.decode(file.bytes).includes("syntax_error"));
      const source = sourceFile ? decoder.decode(sourceFile.bytes) : "";
      const errorLine = sourceFile ? source.split("\n").findIndex((line) => line.includes("syntax_error")) + 1 : 0;
      const diagnostics = sourceFile
        ? [{
            severity: "error" as const,
            code: "MOCK_SYNTAX_ERROR",
            message: "Fixture marker: this diagnostic is generated by the UI mock, not an HDL compiler.",
            path: sourceFile.path,
            line: errorLine,
            column: Math.max(1, source.split("\n")[errorLine - 1]?.indexOf("syntax_error") ?? 0) + 1,
          }]
        : [];
      return {
        compileId: `mock-compile-${++compileCounter}`,
        projectId: input.projectId,
        snapshotId: input.snapshotId,
        success: diagnostics.length === 0,
        diagnostics,
      };
    },
    async run(input: RunRequest): Promise<RunResult> {
      return {
        runId: `mock-run-${++runCounter}`,
        projectId: input.projectId,
        snapshotId: input.snapshotId,
        status: "failed",
        diagnostics: [{
          severity: "error",
          code: "SIMULATOR_UNAVAILABLE",
          message: "No HDL was executed. The Xezim WASM Worker has not been integrated.",
        }],
        stdout: "",
        stderr: "Mock service only: no simulator is connected.",
        lastTime: { ticks: "0", timescale: input.until.timescale },
      };
    },
  };

  return { workspace, simulation };
}
